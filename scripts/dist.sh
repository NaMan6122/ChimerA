#!/usr/bin/env bash
#
# scripts/dist.sh — cross-compile Chimera's release artifacts.
#
#   CHIMERA_VERSION=v0.4.0 ./scripts/dist.sh
#   ./scripts/dist.sh                    # version from git describe
#
# Produces in dist/:
#   chimera_<ver>_<os>_<arch>.tar.gz     all three binaries + LICENSE + README
#   chimera_<ver>_windows_amd64.zip
#   checksums.txt                        sha256 over every artifact
#   chimera.rb                           Homebrew formula for the tap
#
# All builds are CGO_ENABLED=0: the binaries are fully static and cross-compile
# from any host (verified: darwin+linux, amd64+arm64, from an arm64 Mac).
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
DIST="$ROOT/dist"
REPO="NaMan6122/ChimerA"

VERSION=${CHIMERA_VERSION:-$(git -C "$ROOT" describe --tags --always --dirty 2>/dev/null || echo dev)}
VERNUM=${VERSION#v}   # artifact filenames carry no leading "v"

case "$VERSION" in
    v[0-9]*) ;; *) echo "note: version '$VERSION' is not a v-prefixed tag; the formula will not resolve" ;;
esac

LDFLAGS="-s -w -X main.version=$VERSION"

# (goos goarch) pairs; every tarball packages all three binaries together.
PLATFORMS=(
    "darwin amd64"
    "darwin arm64"
    "linux  amd64"
    "linux  arm64"
)
BINARIES=("chimera ./cmd/chimera" "chimera-spin ./cmd/chimera-spin" "chimera-chat ./cmd/chimera-chat")

rm -rf "$DIST"
mkdir -p "$DIST"

sum() { # portable sha256 of a file, hex only
    if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{print $1}'
    else shasum -a 256 "$1" | awk '{print $1}'; fi
}

echo "==> chimera dist: version=$VERSION cgo=off go=$(go version | awk '{print $3}')"

build_unix() {
    local goos=$1 goarch=$2
    local name="chimera_${VERNUM}_${goos}_${goarch}"
    local stage="$DIST/$name"
    mkdir -p "$stage"
    for pkg in "${BINARIES[@]}"; do
        set -- $pkg
        CGO_ENABLED=0 GOOS=$goos GOARCH=$goarch \
            go build -C "$ROOT" -trimpath -ldflags "$LDFLAGS" -o "$stage/$1" "$2"
    done
    cp "$ROOT/LICENSE" "$ROOT/README.md" "$stage/"
    ( cd "$stage" && COPYFILE_DISABLE=1 tar -czf "$DIST/$name.tar.gz" chimera chimera-spin chimera-chat LICENSE README.md )
    rm -rf "$stage"
    printf '    %s.tar.gz (%s)\n' "$name" "$(du -h "$DIST/$name.tar.gz" | cut -f1)"
}

build_windows() {
    local name="chimera_${VERNUM}_windows_amd64"
    local stage="$DIST/$name"
    mkdir -p "$stage"
    for pkg in "${BINARIES[@]}"; do
        set -- $pkg
        CGO_ENABLED=0 GOOS=windows GOARCH=amd64 \
            go build -C "$ROOT" -trimpath -ldflags "$LDFLAGS" -o "$stage/$1.exe" "$2"
    done
    cp "$ROOT/LICENSE" "$ROOT/README.md" "$stage/"
    ( cd "$stage" && zip -q -r "$DIST/$name.zip" . )
    rm -rf "$stage"
    printf '    %s.zip (%s)\n' "$name" "$(du -h "$DIST/$name.zip" | cut -f1)"
}

for p in "${PLATFORMS[@]}"; do build_unix $p; done
build_windows

( cd "$DIST" && for f in chimera_*.tar.gz chimera_*.zip; do echo "$(sum "$f")  $f"; done > checksums.txt )
printf '    checksums.txt (%d artifacts)\n' "$(wc -l < "$DIST/checksums.txt" | tr -d ' ')"

sha_for() { awk -v f="$1" '$2==f {print $1}' "$DIST/checksums.txt"; }

# --- Homebrew formula --------------------------------------------------------
# The tap (NaMan6122/homebrew-chimera) installs whichever url matches the
# host: brew taps don't support per-platform formula selection, so the four
# url/sha pairs are declared with on_macos/on_linux + Hardware::CPU.
cat > "$DIST/chimera.rb" <<EOF
# Generated by scripts/dist.sh for $VERSION — do not edit by hand.
# Update the tap with: curl -fsSLo Formula/chimera.rb \\
#   https://github.com/$REPO/releases/download/$VERSION/chimera.rb
class Chimera < Formula
  desc "Your chat subscriptions as an OpenAI-compatible API"
  homepage "https://github.com/$REPO"
  version "$VERNUM"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    if Hardware::CPU.intel?
      url "https://github.com/$REPO/releases/download/$VERSION/chimera_${VERNUM}_darwin_amd64.tar.gz"
      sha256 "$(sha_for "chimera_${VERNUM}_darwin_amd64.tar.gz")"
    else
      url "https://github.com/$REPO/releases/download/$VERSION/chimera_${VERNUM}_darwin_arm64.tar.gz"
      sha256 "$(sha_for "chimera_${VERNUM}_darwin_arm64.tar.gz")"
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "https://github.com/$REPO/releases/download/$VERSION/chimera_${VERNUM}_linux_amd64.tar.gz"
      sha256 "$(sha_for "chimera_${VERNUM}_linux_amd64.tar.gz")"
    else
      url "https://github.com/$REPO/releases/download/$VERSION/chimera_${VERNUM}_linux_arm64.tar.gz"
      sha256 "$(sha_for "chimera_${VERNUM}_linux_arm64.tar.gz")"
    end
  end

  def install
    bin.install "chimera", "chimera-spin", "chimera-chat"
  end

  def caveats
    <<~EOS
      The gateway reads .env, auth_data/ and browser_data/ from its working
      directory. Before the first browserless start:
        chimera auth login <provider>       # opens a browser once
        TRANSPORT=webapi PROVIDER=chatgpt chimera
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/chimera -version")
    assert_match version.to_s, shell_output("#{bin}/chimera-spin -version")
    assert_match version.to_s, shell_output("#{bin}/chimera-chat -version")
  end
end
EOF
printf '    chimera.rb (Homebrew formula)\n'

echo "==> dist/ ready: $(ls "$DIST" | wc -l | tr -d ' ') files"
